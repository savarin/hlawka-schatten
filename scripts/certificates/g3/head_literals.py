"""Reconstruct the integer table declarations in HlawkaSchatten/BelowExponent/G3HeadDataCore.lean."""

import argparse
import hashlib
from pathlib import Path
import sys


SCALE = 2**28


def rounded_power(numerator, denominator, power, degree):
    """Round SCALE * (numerator / denominator) ** (power / degree) to nearest, ties to even."""
    target = numerator**power * SCALE**degree
    divisor = denominator**power
    quotient = target // divisor

    # Find the integer below the root, then compare the exact value with the half-integer.
    lo = 0
    hi = 1 << ((quotient.bit_length() + degree - 1) // degree)
    while hi - lo > 1:
        mid = (hi + lo) // 2
        if mid**degree <= quotient:
            lo = mid
        else:
            hi = mid
    midpoint = (2 * lo + 1)**degree * divisor
    doubled = target << degree
    return lo + int(midpoint < doubled or (midpoint == doubled and lo % 2 == 1))


def power_rows():
    rows = [(0, 0)]
    for n in range(1, 2049):
        lower, upper = ((65, 41), (84, 53)) if n <= 1024 else ((84, 53), (65, 41))
        rows.append((max(0, rounded_power(n, 1024, *lower) - 2),
                     rounded_power(n, 1024, *upper) + 2))
    return rows


def ratio_rows():
    return [(max(0, rounded_power(i, 250, 12, 25) - 2),
             rounded_power(i + 1, 250, 139, 1325) + 2,
             rounded_power(250, 499 - i, 31, 53) + 2)
            for i in range(50)]


def array_declaration(name, element, entries, closing="]"):
    strings = [str(entry) for entry in entries]
    lines = ["  " + ", ".join(strings[i:i + 4]) for i in range(0, len(strings), 4)]
    return f"def {name} : Array {element} := #[\n" + ",\n".join(lines) + closing


def literal_section():
    rows = power_rows()
    names = []
    blocks = []
    for start in range(0, len(rows), 64):
        name = f"headPowerBlock{start // 64}"
        names.append(name)
        blocks.append(array_declaration(name, "(ℕ × ℕ)", rows[start:start + 64]))
    blocks.append(array_declaration("headPowerBlocks", "(Array (ℕ × ℕ))", names, closing=" ]"))
    blocks.append(array_declaration("headRatioRows", "(ℕ × ℕ × ℕ)", ratio_rows()))
    return ("\n\n".join(blocks) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", type=Path, metavar="MODULE",
                        help="compare the generated bytes to the tables in the specified Lean module")
    args = parser.parse_args()
    generated = literal_section()
    if args.check is None:
        sys.stdout.buffer.write(generated)
        return
    module = args.check.read_bytes()
    start = module.index(b"def headPowerBlock0 :")
    stop = module.index(b"def headPower (n", start)
    if module[start:stop] != generated:
        raise SystemExit("The generated head tables differ from the specified module")
    print(f"Matched 2,049 power pairs and 50 ratio triples in {len(generated)} bytes.")
    print("SHA-256", hashlib.sha256(generated).hexdigest())


if __name__ == "__main__":
    main()
