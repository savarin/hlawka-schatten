#!/usr/bin/env python3
"""Put a generator's Lean output into the layout of the committed proof files.

The generators write plain modules: `module`, the imports, `@[expose] public section`, the namespaces, and
sometimes a `-- Generated by <script> ...` note. A committed file of `HlawkaSchatten/BelowExponent` adds:

  - the library's licence header (replacing any other licence comment);
  - a one-line description right after the imports, naming the region and, where the generator left a
    note, the script that produced the file (the note itself is dropped);
  - the elaboration settings the proof was written under (`autoImplicit` and `relaxedAutoImplicit` on, and
    Mathlib's standard linter set off where Mathlib is in reach), right after the description;
  - the namespace `HlawkaSchatten.BelowExponent.TC` for the bulk tangent checker's `TC`.

`to_repo` applies exactly these changes, so a regenerated file can be compared byte for byte with the
checkout. Usage as a command: `python3 layout.py FILE.lean...` rewrites the files in place; each path must
lie under `HlawkaSchatten/BelowExponent/` in this checkout, or name its place there with `--as`.
"""
import argparse
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROOF = "HlawkaSchatten/BelowExponent/"
NAMESPACE = "HlawkaSchatten.BelowExponent"
HEADER = ("/-\nCopyright (c) 2026 Ezzeri Esa. All rights reserved.\n"
          "Released under Apache 2.0 license as described in the file LICENSE.\n"
          "Authors: Ezzeri Esa\n-/\n")
SETTINGS = ["set_option autoImplicit true", "set_option relaxedAutoImplicit true",
            "set_option linter.mathlibStandardSet false"]
IMPORT_RE = re.compile(r"^(\s*(?:(?:public|private|meta)\s+)*import\s+)(.*)$")
NOTE_RE = re.compile(r"^-- Generated by (\S+?)(?: (.+?))?\.?$")

# What each generated folder holds (from the files that use it).
FOLDER_DOC = {
    "G3PCutBands": "Certificate data for the ordered G3 vertex corner: cut band piece `{stem}`.",
    "Vertex/SideCutCorners": "Checked corner data for the vertex side region: `{stem}`.",
    "Vertex/SideConeCoarseData": "Coarse near-cone certificate data for the vertex side region: `{stem}`.",
    "FSlabData": "Exact data for the weighted F-slab facet checks: `{stem}`.",
    "FacetArchive": "Archived facet prism certificate data: `{stem}`.",
    "Vertex/VcCutCorners": "Checked corner data shared by the vertex middle and band regions: `{stem}`.",
    "Vertex/CornerPowerData": "Checked powers for the VC and SC corner rectangle certificates: `{stem}`.",
    "Vertex/VcCornerData": "Outer corner points for the vertex middle and band regions: `{stem}`.",
    "FacetG2": "Certificate data for the G2 facet triangles: `{stem}`.",
    "Vertex/SideCornerData": "Row tables for the closed SC row checks at a shared parameter corner: `{stem}`.",
    "Tangent/Cells": "Bulk tangent certificate for the E2 cells: `{stem}`.",   # covers its subfolders
}
PREFIX_FOLDERS = ("Tangent/Cells",)


def set_header(text):
    if text.startswith(HEADER):
        return text
    m = re.match(r"/-(?![!-])[\s\S]*?-/\n", text)
    if m and re.search(r"SPDX-License-Identifier|Copyright", m.group(0)):
        return HEADER + "\n" + text[m.end():].lstrip("\n")
    return HEADER + "\n" + text


def imports_of(text):
    found = []
    for line in text.split("\n"):
        m = IMPORT_RE.match(line)
        if m:
            found += [t for t in m.group(2).partition("--")[0].split() if t != "all"]
    return found


_REACH = {}


def reaches_mathlib(text, root=ROOT):
    """Whether Mathlib is among the imports, directly or through other modules of the proof folder."""
    def go(module):
        if module not in _REACH:
            _REACH[module] = False
            path = root / (module.replace(".", "/") + ".lean")
            _REACH[module] = path.is_file() and any(
                i.startswith("Mathlib") or (i.startswith(NAMESPACE + ".") and go(i))
                for i in imports_of(path.read_text(encoding="utf-8")))
        return _REACH[module]
    return any(i.startswith("Mathlib") or (i.startswith(NAMESPACE + ".") and go(i)) for i in imports_of(text))


def add_settings(text, with_mathlib):
    if SETTINGS[0] in text:
        return text
    settings = SETTINGS if with_mathlib else SETTINGS[:2]
    lines = text.split("\n")
    i, in_comment, last_import, module_at = 0, False, None, None
    while i < len(lines):
        s = lines[i].strip()
        if in_comment:
            in_comment = "-/" not in s
        elif s.startswith("/-") and not s.startswith(("/-!", "/--")):
            in_comment = "-/" not in s[2:]
        elif s == "" or s.startswith("--"):
            pass
        elif s == "module":
            module_at = i
        elif IMPORT_RE.match(lines[i]):
            last_import = i
        else:
            break
        i += 1
    at = last_import if last_import is not None else module_at
    lines[at + 1:at + 1] = [""] + settings
    return "\n".join(lines)


def rename(text):
    text = re.sub(r"^namespace TC[ \t]*$", f"namespace {NAMESPACE}.TC", text, flags=re.M)
    return re.sub(r"^end TC[ \t]*$", f"end {NAMESPACE}.TC", text, flags=re.M)


def _last_import(lines):
    return max(i for i, line in enumerate(lines) if IMPORT_RE.match(line))


def _doc_end(lines, k):
    """Index of the line closing the doc-string opened at line k (Lean comments nest)."""
    depth = 0
    for n in range(k, len(lines)):
        pos, line = 0, lines[n]
        while pos < len(line):
            if line.startswith("/-", pos):
                depth, pos = depth + 1, pos + 2
            elif line.startswith("-/", pos):
                depth, pos = depth - 1, pos + 2
                if depth == 0:
                    return n
            else:
                pos += 1
    raise ValueError("unclosed doc-string")


def settings_after_doc(text):
    """Move the settings that sit between the imports and the module doc-string to just after it."""
    lines = text.split("\n")
    i = _last_import(lines) + 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    j = i
    while j < len(lines) and lines[j].startswith("set_option "):
        j += 1
    k = j
    while k < len(lines) and not lines[k].strip():
        k += 1
    if j == i or k >= len(lines) or not lines[k].startswith("/-!"):
        return text
    end = _doc_end(lines, k)
    if not lines[end].rstrip().endswith("-/"):
        return text
    rest = lines[end + 1:]
    while rest and not rest[0].strip():
        rest = rest[1:]
    return "\n".join(lines[:_last_import(lines) + 1] + [""] + lines[k:end + 1] + [""] + lines[i:j]
                     + ([""] + rest if rest else [""]))


def take_note(text):
    """Remove a `-- Generated by` note; return the text and (script, rest) or None."""
    lines = text.split("\n")
    for n, line in enumerate(lines):
        m = NOTE_RE.match(line)
        if m:
            del lines[n]
            if 0 < n < len(lines) and not lines[n - 1].strip() and not lines[n].strip():
                del lines[n]
            return "\n".join(lines), (m.group(1), m.group(2))
    return text, None


def _sentence(note):
    script, rest = note
    return f"Generated by `{script}`" + (f" {rest}" if rest else "") + "."


def _wrap(doc):
    return textwrap.wrap(f"/-! {doc} -/", width=100, break_long_words=False, break_on_hyphens=False)


def describe(rel, text, note):
    """Give the file its description right after the imports; fold the generator note into it."""
    lines = text.split("\n")
    at = _last_import(lines)
    k = at + 1
    while k < len(lines) and not lines[k].strip():
        k += 1
    if k < len(lines) and lines[k].startswith("/-!"):          # the file has its own description
        if note is None:
            return text
        end = _doc_end(lines, k)
        if k == end:                                           # one line: extend and rewrap
            body = lines[k][3:].rstrip()[:-2].strip()
            return "\n".join(lines[:k] + _wrap(f"{body} {_sentence(note)}") + lines[end + 1:])
        if lines[end].strip() != "-/":
            raise ValueError(f"{rel}: cannot extend this doc-string")
        return "\n".join(lines[:end] + ["", _sentence(note)] + lines[end:])
    inner = rel[len(PROOF):] if rel.startswith(PROOF) else rel
    folder = inner.rsplit("/", 1)[0] if "/" in inner else ""
    key = next((p for p in PREFIX_FOLDERS if folder == p or folder.startswith(p + "/")), folder)
    parts = []
    if key in FOLDER_DOC:
        parts.append(FOLDER_DOC[key].format(stem=inner[len(key) + 1:-len(".lean")]))
    if note is not None:
        parts.append(_sentence(note))
    if not parts:
        return text
    return "\n".join(lines[:at + 1] + [""] + _wrap(" ".join(parts)) + lines[at + 1:])


def to_repo(rel, text, root=ROOT):
    """The committed form of a generated file at `rel` (a path under HlawkaSchatten/BelowExponent/)."""
    text = rename(text)
    text = add_settings(set_header(text), reaches_mathlib(text, root))
    text, note = take_note(settings_after_doc(text))
    return describe(rel, text, note)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="+", type=Path)
    parser.add_argument("--as", dest="place", help="the file's path in the checkout (one file only)")
    args = parser.parse_args()
    if args.place and len(args.files) != 1:
        parser.error("--as takes exactly one file")
    for path in args.files:
        rel = args.place or path.resolve().relative_to(ROOT).as_posix()
        if not rel.startswith(PROOF):
            parser.error(f"{rel} is not under {PROOF}")
        path.write_text(to_repo(rel, path.read_text(encoding="utf-8")), encoding="utf-8")


if __name__ == "__main__":
    main()
