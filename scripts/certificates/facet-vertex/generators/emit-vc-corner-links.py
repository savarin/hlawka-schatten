"""Encode the 882 normalized VC corner points and the middle/band cell references."""

import argparse
import csv
from fractions import Fraction
import json
from pathlib import Path
import runpy


HERE = Path(__file__).resolve().parent
NAMESPACE = "HlawkaSchatten.BelowExponent.Vertex"
FAMILY = "VcCornerData"
POINT_IMPORT = f"{NAMESPACE}.CornerPointData"
DEST = HERE.parent / "lean" / "HlawkaSchatten/BelowExponent" / "Vertex" / FAMILY
POINTS_PER_FILE = 32


def read_points():
    with (HERE / "vertex-corner-curvature-margins.tsv").open() as source:
        points = [row for row in csv.DictReader(source, delimiter="\t") if row["family"] == "VC"]
    if [int(row["corner"]) for row in points] != list(range(882)):
        raise ValueError("Expected the 882 indexed VC corner points")
    return [
        (tuple(Fraction(row[key]) for key in ("a", "b", "eta")),
         tuple(Fraction(row[f"margin{j}"]) for j in range(3)))
        for row in points
    ]


def write_module(name, imports, declarations):
    source = ["module", "", *(f"public import {item}" for item in imports),
              "", "@[expose] public section", "", f"namespace {NAMESPACE}",
              "", "-- Generated by scripts/certificates/facet-vertex/generators/emit-vc-corner-links.py.", *declarations,
              "", f"end {NAMESPACE}", ""]
    path = DEST / f"{name}.lean"
    text = "\n".join(source)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def write_points(points):
    root_intervals = runpy.run_path(str(HERE / "vertex_root_witnesses.py"))["root_intervals"]
    modules = []
    arrays = []
    for start in range(0, len(points), POINTS_PER_FILE):
        name = f"Points{start:03}"
        array = f"vcOuterPoints{start:03}"
        modules.append(f"{NAMESPACE}.{FAMILY}.{name}")
        arrays.append(array)
        declarations = []
        names = []
        for i, (coord, margins) in enumerate(points[start:start + POINTS_PER_FILE], start):
            point = f"vcOuterP{i:03}"
            names.append(point)
            a, b, eta = coord
            margin_values = ", ".join(map(str, margins))
            roots = ", ".join(f"⟨{lo}, {hi}⟩" for lo, hi in root_intervals([(p, p) for p in coord]))
            declarations.extend([
                f"def {point} : SideCornerEntry := ⟨{a}, {b}, {eta}, #v[{margin_values}]⟩",
                f"def {point}Roots : Fin 3 → RatBounds := ![{roots}]",
                f"theorem {point}_roots : {point}.cell.rootsOK {point}Roots = true := by decide +kernel",
                "",
            ])
        declarations.extend([f"def {array} : Array SideCornerEntry := #[", "  " + ",\n  ".join(names) + "]"])
        write_module(name, [POINT_IMPORT], declarations)
    write_module("PointTable", modules, [
        "def vcOuterPointBlocks : List (Array SideCornerEntry) := [",
        "  " + ",\n  ".join(arrays) + "]",
        "", "def vcOuterPoints : Array SideCornerEntry :=",
        "  " + " ++\n  ".join(arrays),
        "", "theorem vcOuterPoints_toList :",
        "    vcOuterPointBlocks.flatMap Array.toList = vcOuterPoints.toList := by",
        "  simp only [vcOuterPointBlocks, vcOuterPoints, List.flatMap_cons, List.flatMap_nil,",
        "    Array.toList_append, List.append_nil, List.append_assoc]",
    ])


def write_links(cells, label, certificates):
    name = f"Vc{label}CornerLinks"
    value = f"vc{label}OuterCellLinks"
    links = ("#v[" + ", ".join(map(str, entry["corners"])) + "]" for entry in cells)
    certificate_value = certificates[0].lower() + certificates[1:]
    write_module(name, [f"{NAMESPACE}.SideCornerLinks", f"{NAMESPACE}.{FAMILY}.PointTable",
                        f"{NAMESPACE}.{certificates}"], [
        f"def {value} : List (Vector Nat 8) := [",
        "  " + ",\n  ".join(links) + "]",
        "", "set_option maxRecDepth 30000 in", "set_option maxHeartbeats 0 in",
        f"theorem {value}_checked :",
        "    sideCornerGridLookupOK (sideCornerBlockLookup vcOuterPointBlocks)",
        f"      {certificate_value} {value} = true := by",
        "  decide +kernel",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("corner_index", type=Path, help="JSON from vertex_corner_index.py")
    args = parser.parse_args()
    data = json.loads(args.corner_index.read_text())["VC"]
    points = read_points()
    if [coord for coord, _ in points] != [tuple(map(Fraction, point)) for point in data["points"]]:
        raise ValueError("The corner coordinates do not match the margin table")
    cells = data["cells"]
    middle = [entry for entry in cells if entry["zone"] == "VcM"]
    band = [entry for entry in cells if entry["zone"] == "VcS1"]
    if len(middle) != 250 or len(band) != 212 or len(cells) != 462:
        raise ValueError("Expected 250 refined VC-M cells and 212 VC-S1 cells")
    refined = {entry["parent"] for entry in middle if entry["child"] != 0}
    # vcMiddleRefinedGrid places all replacement children after the original cells.
    middle.sort(key=lambda entry: (entry["parent"] in refined, entry["parent"], entry["child"]))
    if any(len(set(entry["corners"])) != 8 for entry in cells):
        raise ValueError("Every cell needs eight distinct corner references")
    if {index for entry in cells for index in entry["corners"]} != set(range(len(points))):
        raise ValueError("The cell references do not use exactly the shared point set")
    DEST.mkdir(parents=True, exist_ok=True)
    write_points(points)
    write_links(middle, "Middle", "VcMCurvatureCertificates")
    write_links(band, "Band", "VcS1CurvatureCertificates")
    print(f"{len(points)} points, {3 * len(points)} radical brackets, {len(cells)} cells, {8 * len(cells)} references")


if __name__ == "__main__":
    main()
