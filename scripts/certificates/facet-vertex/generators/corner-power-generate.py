"""Generate shared dyadic power witnesses for the outer VC and SC row grid."""

from decimal import Decimal, localcontext
from fractions import Fraction as Q
from pathlib import Path
import re


HERE = Path(__file__).resolve().parent
VERTEX = HERE.parent / "lean" / "HlawkaSchatten/BelowExponent" / "Vertex"
PREFIX = "HlawkaSchatten.BelowExponent.Vertex"
FAMILY = "CornerPowerData"
SCALE = 2**64
Q_LOWER = Q(1054, 665)
Q_UPPER = Q(485, 306)
CHORD_CHUNK = 64


def candidate(x, exponent, upper):
    if x in (0, 1):
        return int(x) * SCALE
    with localcontext() as ctx:
        ctx.prec = 85
        value = Decimal(x.numerator) / x.denominator
        power = Decimal(exponent.numerator) / exponent.denominator
        n = int(value**power * SCALE) + (2 if upper else -2)
    a, b = exponent.numerator, exponent.denominator
    expected = x.numerator**a * SCALE**b
    actual = n**b * x.denominator**a
    assert (expected <= actual if upper else actual <= expected), (x, exponent, n)
    return n


def bounds(x):
    x = abs(x)
    lo, hi = (Q_UPPER, Q_LOWER) if x <= 1 else (Q_LOWER, Q_UPPER)
    return candidate(x, lo, False), candidate(x, hi, True)


def write(name, imports, body):
    path = VERTEX / FAMILY / (name + ".lean")
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["module", "", *(f"public import {m}" for m in imports), "", "@[expose] public section",
             "", f"namespace {PREFIX}", "", "-- Generated by scripts/certificates/facet-vertex/generators/corner-power-generate.py.",
             *body, "", f"end {PREFIX}", ""]
    text = "\n".join(lines)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def rational_bound(x):
    lo, hi = bounds(x)
    return f"⟨{Q(lo, SCALE)}, {Q(hi, SCALE)}⟩"


def axis_table():
    nodes_source = (VERTEX / "CornerGridData.lean").read_text()
    match = re.search(r"def outerNodes : Vector ℚ 35 := #v\[([^]]+)\]", nodes_source)
    nodes = [Q(x.strip()) for x in match[1].split(",")]
    assert len(nodes) == 35 and sorted(set(nodes)) == nodes
    mids = [(a + b) / 2 for a, b in zip(nodes, nodes[1:])]
    assert all(mids)
    write("Axis", [f"{PREFIX}.CornerGridData"], [
        "def outerNodeQTable : Vector RatBounds 35 := #v[",
        "  " + ",\n  ".join(map(rational_bound, nodes)) + "]", "",
        "def outerMidpointQTable : Vector RatBounds 34 := #v[",
        "  " + ",\n  ".join(map(rational_bound, mids)) + "]",
    ])


def chord_table():
    modules, names = [], []
    for start in range(0, 1026, CHORD_CHUNK):
        name = f"Chord{start:04}"
        numbers = []
        for i in range(start, min(start + CHORD_CHUNK, 1026)):
            x = Q(i, 256)
            numbers.append(str(candidate(x, Q_LOWER if x <= 1 else Q_UPPER, True)))
        names.append(f"outerChordBlock{start:04}")
        modules.append(f"{PREFIX}.{FAMILY}.{name}")
        write(name, [f"{PREFIX}.CornerGridData"],
              [f"def {names[-1]} : Array ℤ := #[", "  " + ",\n  ".join(numbers) + "]"])
    write("Chord", modules,
          ["def outerChordQTable : Array (Array ℤ) := #[", "  " + ",\n  ".join(names) + "]"])


def wide_axis_table():
    modules, names = [], []
    for start in range(0, 513, CHORD_CHUNK):
        name = f"WideAxis{start:03}"
        names.append(f"outerWideQBlock{start:03}")
        modules.append(f"{PREFIX}.{FAMILY}.{name}")
        values = [rational_bound(Q(i, 512)) for i in range(start, min(start + CHORD_CHUNK, 513))]
        write(name, [f"{PREFIX}.CornerGridData"],
              [f"def {names[-1]} : Array RatBounds := #[", "  " + ",\n  ".join(values) + "]"])
    write("WideAxis", modules,
          ["def outerWideQTable : Array (Array RatBounds) := #[", "  " + ",\n  ".join(names) + "]"])


if __name__ == "__main__":
    axis_table()
    chord_table()
    wide_axis_table()
    print("69 axis brackets, 1,026 remainder chord upper bounds and 513 half-grid axis brackets")
