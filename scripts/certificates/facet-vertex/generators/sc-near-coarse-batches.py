"""Assemble and measure the 510 closed side near-cone certificates."""

import argparse
import os
from pathlib import Path
import signal
import subprocess
import time


PROJECT = Path(__file__).resolve().parents[1] / "lean"
LAKE = Path.home() / ".elan/toolchains/leanprover--lean4---v4.36.0/bin/lake"
FAMILY = "HlawkaSchatten.BelowExponent.Vertex.SideConeCoarseData"
SOURCE = PROJECT.joinpath(*FAMILY.split("."))
COUNT = 510
CHUNK = 32


def write_module(name, imports, body):
    SOURCE.mkdir(parents=True, exist_ok=True)
    destination = SOURCE / f"{name}.lean"
    content = "\n".join([
        "module", "", *(f"public import {module}" for module in imports), "",
        "@[expose] public section", "", "namespace HlawkaSchatten.BelowExponent.Vertex", "",
        "-- Generated by scripts/certificates/facet-vertex/generators/sc-near-coarse-batches.py.", "", *body, "",
        "end HlawkaSchatten.BelowExponent.Vertex", "",
    ])
    if not destination.exists() or destination.read_text() != content:
        destination.write_text(content)


def assemble_sources():
    joins = []
    for first in range(0, COUNT, CHUNK):
        indices = range(first, min(first + CHUNK, COUNT))
        name = f"Block{first:03}"
        joins.append(name)
        rows = [f"  ⟨scCoarseProd{i}Cell, scCoarseProd{i}Near⟩" for i in indices]
        write_module(
            name,
            ["HlawkaSchatten.BelowExponent.Vertex.SideConeFastJoin", *(f"{FAMILY}.Cell{i}" for i in indices)],
            [f"def scCoarseProd{name} : List SideFastCellCertificate := [",
             ",\n".join(rows) + "]"],
        )
    write_module(
        "Complete", [f"{FAMILY}.{name}" for name in joins],
        ["def scCoarseProdGrid : List SideFastCellCertificate :=",
         "  " + " ++\n  ".join(f"scCoarseProd{name}" for name in joins), "",
         "set_option maxRecDepth 30000 in", "set_option maxHeartbeats 0 in",
         "theorem scCoarseProdGrid_cells :",
         "    scCoarseProdGrid.map SideFastCellCertificate.cell = scParameterGrid := by",
         "  decide +kernel", "",
         "theorem sideNearConeCoarse_box_grid : ∀ c ∈ scParameterGrid, ∀ row ∈ sideRowGrid,",
         "    SideConeOn c (sideURange row.1) (sideVRange row.2) :=",
         "  sideFastFamily_sound scCoarseProdGrid_cells"],
    )
    return joins


def build(modules, logs):
    command = [LAKE, "-d", PROJECT, "build", *(f"{FAMILY}.{name}" for name in modules)]
    start = time.monotonic()
    with (logs / f"{modules[0]}-{modules[-1]}.txt").open("w") as report:
        process = subprocess.Popen(command, stdout=report, stderr=subprocess.STDOUT,
                                   start_new_session=True)
        expired = False
        try:
            while True:
                pid, status, usage = os.wait4(process.pid, os.WNOHANG)
                if pid:
                    break
                if time.monotonic() - start >= 300:
                    expired = True
                    os.killpg(process.pid, signal.SIGKILL)
                    _, status, usage = os.wait4(process.pid, 0)
                    break
                time.sleep(0.25)
        except KeyboardInterrupt:
            os.killpg(process.pid, signal.SIGTERM)
            process.wait()
            raise
        process.returncode = os.waitstatus_to_exitcode(status)
    passed = process.returncode == 0 and not expired
    wall = time.monotonic() - start
    cpu = usage.ru_utime + usage.ru_stime
    print(f"{'CHECKED' if passed else 'FAILED'} {' '.join(modules)} "
          f"{wall:.2f}s wall {cpu:.2f}s CPU {usage.ru_maxrss} peak-RSS bytes", flush=True)
    return passed


def replay(modules, args):
    for first in range(0, len(modules), args.workers):
        wave = modules[first:first + args.workers]
        deadline = time.monotonic() + 600
        incoming = args.staged_sources or SOURCE
        for name in wave:
            proposed = incoming / f"{name}.lean"
            while True:
                if proposed.is_file():
                    content = proposed.read_text()
                    if content.endswith("end HlawkaSchatten.BelowExponent.Vertex\n"):
                        break
                if "uncaught exception:" in args.prepare_log.read_text() or time.monotonic() > deadline:
                    raise RuntimeError(f"Preparer did not supply {proposed}")
                time.sleep(2)
            if incoming != SOURCE:
                installed = SOURCE / proposed.name
                if not installed.exists() or installed.read_text() != content:
                    temporary = installed.with_suffix(".pending")
                    temporary.write_text(content)
                    temporary.replace(installed)
        if not build(wave, args.logs):
            return False
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workers", type=int, default=3)
    parser.add_argument("--logs", type=Path, required=True)
    parser.add_argument("--prepare-log", type=Path, required=True)
    parser.add_argument("--staged-sources", type=Path)
    args = parser.parse_args()
    if args.workers < 1:
        parser.error("--workers must be positive")
    args.logs.mkdir(parents=True, exist_ok=True)
    joins = assemble_sources()
    for first, join in zip(range(0, COUNT, CHUNK), joins, strict=True):
        cells = [f"Cell{i}" for i in range(first, min(first + CHUNK, COUNT))]
        if not replay(cells, args) or not build([join], args.logs):
            return 1
    return int(not build(["Complete"], args.logs))


if __name__ == "__main__":
    raise SystemExit(main())
