"""Encode the common SC margin points, fifth-root brackets and exact cell references."""

import argparse
import csv
from fractions import Fraction as Q
from hashlib import sha256
from itertools import product
from pathlib import Path
import runpy


HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent / "lean"
ARCHIVE = HERE / "vertex-corner-curvature-margins.tsv"
CUT_ARCHIVE = HERE / "vertex-curvature-cut-shared-margins.tsv"
FIFTH_ROOTS = HERE / "vertex_root_witnesses.py"
PREFIX = "HlawkaSchatten.BelowExponent.Vertex"
FAMILY = "SideCornerData"
CUT_FAMILY = "SideCutCorners"
RECORDS_PER_FILE = 32
ARCHIVE_SHA256 = "7a782e09a9b5b10e4f174e8bf8012fe6a758b7fb62e40b6b5c3b6138387162eb"
CUT_ARCHIVE_SHA256 = "8b8e2d3a27c15c9b0f0429195bdd2ee2d9aa7e209f69b0f298dbec4e51228156"


def read_points(archive=ARCHIVE, expected_sha=ARCHIVE_SHA256):
    raw = archive.read_bytes()
    if sha256(raw).hexdigest() != expected_sha:
        raise ValueError(f"The shared margin table changed: {archive}")
    rows = [r for r in csv.DictReader(raw.decode().splitlines(), delimiter="\t") if r["family"] == "SC"]
    points = []
    for i, r in enumerate(rows):
        assert int(r["corner"]) == i
        coord = tuple(Q(r[f]) for f in ("a", "b", "eta"))
        margin = tuple(Q(r[f"margin{j}"]) for j in range(3))
        points.append((coord, margin))
    assert len(points) == len({p for p, _ in points}) == 880
    return points


def sc_cells():
    depths = (
        [Q(k, 40) for k in range(5)],
        [Q(1, 10), Q(9, 80), Q(1, 8)],
        [Q(1, 8), Q(11, 80), Q(3, 20), Q(13, 80), Q(1, 6)],
    )
    for depth in depths:
        for a, start in (((Q(0), Q(1, 80)), 15), ((Q(1, 80), Q(1, 40)), 14)):
            for n in range(start, 40):
                b = Q(n, 80), Q(n + 1, 80)
                for eta in zip(depth, depth[1:]):
                    yield a, b, eta


def write(name, imports, body, family=FAMILY, *, module_doc=()):
    source = ["module", "", *(f"public import {m}" for m in imports), *module_doc,
              "", "@[expose] public section", "", f"namespace {PREFIX}",
              "", "-- Generated by scripts/certificates/facet-vertex/generators/sc-outer-generate.py.", *body, "", f"end {PREFIX}", ""]
    path = PROJECT / "HlawkaSchatten/BelowExponent" / "Vertex" / family / f"{name}.lean"
    path.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(source)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def point_name(i, stem="scOuter"):
    return f"{stem}P{i:03}"


def point_sources(points, family, stem):
    root_intervals = runpy.run_path(str(FIFTH_ROOTS))["root_intervals"]
    for start in range(0, len(points), RECORDS_PER_FILE):
        module = f"Points{start:03}"
        body, names = [], []
        for i, (coord, margin) in enumerate(points[start:start + RECORDS_PER_FILE], start):
            name = point_name(i, stem)
            names.append(name)
            a, b, eta = coord
            m = ", ".join(map(str, margin))
            roots = ", ".join(f"⟨{lo}, {hi}⟩" for lo, hi in root_intervals([(p, p) for p in coord]))
            body += [
                f"def {name} : SideCornerEntry := ⟨{a}, {b}, {eta}, #v[{m}]⟩",
                f"def {name}Roots : Fin 3 → RatBounds := ![{roots}]",
                f"theorem {name}_roots : {name}.cell.rootsOK {name}Roots = true := by decide +kernel",
                "",
            ]
        block = f"{stem}Points{start:03}"
        body += [f"def {block} : Array SideCornerEntry := #[",
                 "  " + ",\n  ".join(names) + "]"]
        write(module, [f"{PREFIX}.CornerPointData"], body, family)
        yield module, block


def build_point_table(points, family, stem):
    groups = list(point_sources(points, family, stem))
    write(
        "PointTable",
        [f"{PREFIX}.{family}.{m}" for m, _ in groups],
        [f"def {stem}PointBlocks : List (Array SideCornerEntry) := [",
         "  " + ",\n  ".join(name for _, name in groups) + "]", "",
         f"def {stem}Points : Array SideCornerEntry :=",
         "  " + " ++\n  ".join(name for _, name in groups), "",
         f"theorem {stem}Points_toList :",
         f"    {stem}PointBlocks.flatMap Array.toList = {stem}Points.toList := by",
         f"  simp only [{stem}PointBlocks, {stem}Points, List.flatMap_cons, List.flatMap_nil,",
         "    Array.toList_append, List.append_nil, List.append_assoc]"],
        family,
    )
    root_blocks = []
    for start in range(0, len(points), RECORDS_PER_FILE):
        name = f"{stem}Roots{start:03}"
        root_blocks += [f"def {name} : Array (Fin 3 → RatBounds) := #[",
                        "  " + ",\n  ".join(f"{point_name(i, stem)}Roots"
                                           for i in range(start, min(start + RECORDS_PER_FILE, len(points)))) + "]",
                        ""]
    write(
        "RootTable",
        [f"{PREFIX}.{family}.PointTable"],
        [*root_blocks, f"def {stem}RootTable : Array (Fin 3 → RatBounds) :=",
         "  " + " ++\n  ".join(f"{stem}Roots{i:03}" for i in range(0, len(points), RECORDS_PER_FILE))],
        family,
    )
    return len(groups)


def build_points_link():
    points = read_points()
    lookup = {point: i for i, (point, _) in enumerate(points)}
    refs = [[lookup[p] for p in product(*cell)] for cell in sc_cells()]
    assert len(refs) == 510 and {i for cell in refs for i in cell} == set(range(880))
    groups = build_point_table(points, FAMILY, "scOuter")
    chunks, link_body = [], []
    for start in range(0, len(refs), RECORDS_PER_FILE):
        name = f"scOuterCellLinks{start:03}"
        chunks.append(name)
        link_body += [f"def {name} : List (Vector Nat 8) := [",
                      "  " + ",\n  ".join("#v[" + ", ".join(map(str, cell)) + "]"
                                         for cell in refs[start:start + RECORDS_PER_FILE]) + "]", ""]
    write(
        "CellTable",
        [f"{PREFIX}.{FAMILY}.PointTable", f"{PREFIX}.SideCornerLinks", f"{PREFIX}.SideCurvatureComplete"],
        [*link_body, "def scOuterCellLinks : List (Vector Nat 8) :=",
         "  " + " ++\n  ".join(chunks),
         "", "set_option maxRecDepth 30000 in", "set_option maxHeartbeats 0 in",
         "theorem scOuterCellLinks_checked :",
         "    sideCornerGridLookupOK (sideCornerBlockLookup scOuterPointBlocks)",
         "      scCurvatureCertificates scOuterCellLinks = true := by",
         "  decide +kernel"],
    )
    print(f"{len(points)} points, {3 * len(points)} radical brackets, {len(refs)} cells, "
          f"{sum(map(len, refs))} references in {groups} point shards")


def build_row_source(index):
    name = point_name(index)
    start = index // RECORDS_PER_FILE * RECORDS_PER_FILE
    body = ["set_option maxRecDepth 30000", "set_option maxHeartbeats 0", ""]
    for chart in range(3):
        body += [f"theorem {name}_face{chart} : scOuterFaceOK {name}Bounds {chart} = true := by",
                 "  decide +kernel", ""]
    module = f"Rows{index:03}"
    write(module, [f"{PREFIX}.SideOuterCheck", f"{PREFIX}.{FAMILY}.Bounds{start:03}"], body)
    return module


def build_witness_sources(family, stem, result, assembly):
    blocks = []
    for start in range(0, 880, RECORDS_PER_FILE):
        indices = range(start, min(start + RECORDS_PER_FILE, 880))
        body = ["set_option maxRecDepth 20000", "set_option maxHeartbeats 0", ""]
        for i in indices:
            name = point_name(i, stem)
            body += [
                f"theorem {name}_outer : {name}.Valid :=",
                f"  scOuterPoint_of_checked_trees {name}_roots {name}_bounds_eq {name}_wide_checks", "",
            ]
        block = f"{stem}Witnesses{start:03}"
        body += [f"theorem {block} :",
                 f"    SideCornerEntriesOK (fun z => ¬ InSideNearCone z) {stem}Points{start:03}.toList :=",
                 "  ⟨" + ",\n   ".join(f"{point_name(i, stem)}_outer" for i in indices) + ", True.intro⟩"]
        module = f"WideWitnesses{start:03}"
        write(module, [f"{PREFIX}.SideOuterWideProof", *(f"{PREFIX}.{family}.Wide{i:03}" for i in indices)], body, family)
        blocks.append((module, block))
    point_body = [
        "set_option maxRecDepth 30000", "set_option maxHeartbeats 0", "",
        f"theorem {stem}Points_checked : SideCornerEntriesOK (fun z => ¬ InSideNearCone z) {stem}Points.toList := by",
        f"  rw [← {stem}Points_toList]",
        f"  simp only [{stem}PointBlocks, List.flatMap_cons, List.flatMap_nil, List.append_nil]",
    ]
    expression = blocks[-1][1]
    for _, block in reversed(blocks[:-1]):
        expression = f"sideCornerEntriesOK_append {block} ({expression})"
    point_body += [f"  exact {expression}"]
    point_imports = [f"{PREFIX}.{family}.{m}" for m, _ in blocks]
    def physical_body(theorem, near_proof=""):
        applied = f"{assembly} {stem}Points_checked {near_proof}".rstrip()
        return [
            f"theorem {theorem} {{t : Profile}} (ht : OrderedInterior t)",
            "    (hmin : minDirection t ≤ 1 / 40) (hmax : maxDirection t ≤ 4 / 5)",
            "    (hdepth : vertexDepth t ≤ 1 / 8) : RowAt criticalQ t :=",
            f"  {applied}",
            "    ht hmin hmax hdepth",
        ]

    if family == CUT_FAMILY:
        write("PointsComplete", [f"{PREFIX}.{family}.PointTable", *point_imports], point_body, family)
        imports = [f"{PREFIX}.{family}.Assembly", f"{PREFIX}.{family}.PointsComplete"]
        options = ["set_option maxRecDepth 30000", "set_option maxHeartbeats 0", ""]
        write("Complete", [*imports, f"{PREFIX}.SideConeFastData.Complete"],
              [*options, *physical_body(result, "sideNearCone_box_grid")], family)
        coarse_doc = (
            "",
            "/-!",
            "# The critical row inequality on the vertex side",
            "",
            "The outer portion uses the checked corner values in `scCutOuterPoints_checked` and cellwise",
            "curvature bounds. The near-cone estimate `sideNearConeCoarse_box_grid` supplies the other",
            "input to `rowAt_vertexSide_of_cut_corners`.",
            "-/", "",
            'set_option autoImplicit false', 'set_option relaxedAutoImplicit false', 'set_option linter.mathlibStandardSet true',
        )
        write("CoarseComplete", [*imports, f"{PREFIX}.SideConeCoarseData.Complete"],
              ["set_option maxRecDepth 30000 in", *physical_body("rowAt_vertexSide_optimized", "sideNearConeCoarse_box_grid")],
              family, module_doc=coarse_doc)
    else:
        write("Complete", [f"{PREFIX}.{family}.Assembly", *point_imports],
              [*point_body, "", *physical_body(result)], family)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cut", action="store_true", help="use the revised curvature budgets in SideCutCorners")
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument("--points", type=int, nargs="+", help="write numeric files for the named corner indices")
    actions.add_argument("--wide-witnesses", action="store_true", help="write shared wide point joins and final theorem")
    args = parser.parse_args()
    if args.points is not None:
        if args.cut:
            parser.error("--points generates only the original fine-grid certificates")
        if any(not 0 <= i < 880 for i in args.points):
            parser.error("corner indices are 0 through 879")
        print(*(build_row_source(i) for i in args.points), sep="\n")
    elif args.wide_witnesses:
        if args.cut:
            build_witness_sources(CUT_FAMILY, "scCutOuter", "rowAt_vertexSide_cut",
                                  "rowAt_vertexSide_of_cut_corners")
        else:
            build_witness_sources(FAMILY, "scOuter", "rowAt_vertexSide",
                                  "rowAt_vertexSide_of_shared_corners")
        print("28 point joins and physical side theorem")
    elif args.cut:
        points = read_points(CUT_ARCHIVE, CUT_ARCHIVE_SHA256)
        if [p for p, _ in points] != [p for p, _ in read_points()]:
            raise ValueError("The revised table changes the coordinate or corner order")
        shards = build_point_table(points, CUT_FAMILY, "scCutOuter")
        print(f"{len(points)} revised points and {3 * len(points)} fifth-root brackets in {shards} shards")
    else:
        build_points_link()
