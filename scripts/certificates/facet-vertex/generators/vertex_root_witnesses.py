"""Produce Lean fifth-root witnesses for the 930 written VC and SC parameter cells."""

import argparse
from fractions import Fraction
import hashlib
from pathlib import Path
import re


ZONES = (
    ("VcM", "vertex/cells_K.txt", 208, "8177f41d45d5fa2b81c66ef8f165aba95944e0c5b9ce7793584b79c8ad15c79a"),
    ("VcS1", "vertex/cells_K_S1.txt", 212, "9ac5379d612f38969e071f05f5d39410477cd3b5b33211b5431f18bf25f16ca6"),
    ("ScS", "vertex-side/cells_K.txt", 204, "ad4d00f062d4906e09267909225ae8a282eaca532b3fd4dc0f1cecab91957add"),
    ("ScD", "vertex-side/cells_K_D.txt", 102, "b66189a2bc04e38480724396cbe5079ba21364bfd54336868b33bbc5965b0751"),
    ("ScE", "vertex-side/cells_K_E.txt", 204, "94698b99410f3fcffd18d7129bfd9703d34faef4c5206a238afea04a49acfdb0"),
)
SCALE = 2**48
PARENTS_PER_FILE = 16
CELL = re.compile(r"^\[([^\]]+)\] x \[([^\]]+)\] x \[([^\]]+)\]:", re.MULTILINE)
HEADER = """module

public import HlawkaSchatten.BelowExponent.Vertex.RadicalCheck

/-! Parent root witnesses generated by vertex_root_witnesses.py. -/

@[expose] public section

namespace HlawkaSchatten.BelowExponent.Vertex

"""


def lower_fifth_root(value):
    """Largest integer n such that (n / SCALE)^5 ≤ value."""
    if value < 0:
        raise ValueError("Expected a nonnegative fifth power")
    target = (value.numerator * SCALE**5) // value.denominator
    lo, hi = 0, 1 << ((target.bit_length() + 4) // 5)
    while hi - lo > 1:
        mid = (hi + lo) // 2
        if mid**5 <= target:
            lo = mid
        else:
            hi = mid
    return lo


def root_intervals(cell):
    a, b, eta = cell
    directions = (a, b, (1-a[1]-b[1], 1-a[0]-b[0]))
    if eta[0] < 0 or any(not 0 <= lo <= hi <= 1 for lo, hi in directions):
        raise ValueError("Parameter cell outside normalized chart")
    depth_lo, depth_hi = (x / (1 + 2*x) for x in eta)
    sigma_lo, sigma_hi = (sum(directions[i][s]*directions[(i+1) % 3][s] for i in range(3))
                          for s in (0, 1))
    if sigma_lo <= 0:
        raise ValueError("Nonpositive radical denominator")
    roots = []
    for j, (e_lo, e_hi) in enumerate(directions):
        k, l = directions[(j+1) % 3], directions[(j+2) % 3]
        base_lo = (1-depth_hi)*(1-e_hi) + depth_lo*k[0]*l[0]
        base_hi = (1-depth_lo)*(1-e_lo) + depth_hi*k[1]*l[1]
        power_lo = base_lo**2 * (1-depth_hi*e_hi)**3 / sigma_hi**2
        power_hi = base_hi**2 * (1-depth_lo*e_lo)**3 / sigma_lo**2
        low = Fraction(lower_fifth_root(power_lo), SCALE)
        high = Fraction(lower_fifth_root(power_hi), SCALE)
        if high**5 < power_hi:
            high += Fraction(1, SCALE)
        if not low**5 <= power_lo <= power_hi <= high**5:
            raise ArithmeticError("Invalid fifth-root enclosure")
        roots.append((low, high))
    return roots


def interval_literal(bounds):
    return f"⟨{bounds[0]}, {bounds[1]}⟩"


def record(name, cell):
    parameters = ", ".join(map(interval_literal, cell))
    roots = ", ".join(map(interval_literal, root_intervals(cell)))
    return f"""def {name}Cell : ParameterCell := ⟨{parameters}⟩
def {name}Roots : Fin 3 → RatBounds := ![{roots}]
theorem {name}_roots_ok : {name}Cell.rootsOK {name}Roots = true := by decide +kernel

"""


def zone_cells(source_root):
    for zone, relative, count, digest in ZONES:
        contents = (source_root / relative).read_bytes()
        if hashlib.sha256(contents).hexdigest() != digest:
            raise ValueError(f"Unexpected source hash for {relative}")
        rows = CELL.findall(contents.decode())
        if not len(rows) == len(set(rows)) == count:
            raise ValueError(f"Unexpected record count for {zone}")
        cells = [[tuple(map(Fraction, bounds.split(","))) for bounds in row] for row in rows]
        if any(lo > hi for cell in cells for lo, hi in cell):
            raise ValueError(f"Reversed interval in {zone}")
        yield zone, cells


def generate(source_root, output):
    output.mkdir(parents=True, exist_ok=True)
    for zone, cells in zone_cells(source_root):
        count = len(cells)
        for start in range(0, count, PARENTS_PER_FILE):
            records = []
            for i, cell in enumerate(cells[start:start+PARENTS_PER_FILE], start):
                records.append(record(f"{zone[0].lower()}{zone[1:]}{i}", cell))
            path = output / f"{zone}{start:03d}.lean"
            data = HEADER + "".join(records) + "end HlawkaSchatten.BelowExponent.Vertex\n"
            if not path.exists() or path.read_text() != data:
                path.write_text(data)
        print(f"{zone} {count} parents, {3*count} rational root intervals", flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_root", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(args.source_root, args.output)
